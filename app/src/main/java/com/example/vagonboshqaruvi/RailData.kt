        val r = regions.find { it.name == region } ?: return Pair(emptyList(), emptyList())
        val main = stations.filter { it.uzel == r.uzel && it.region == region }.map { it.name }
        val rest = stations.filter { it.uzel == r.uzel && it.region == null }.map { it.name }
        return Pair(main, rest)
    }
